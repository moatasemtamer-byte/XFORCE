using System.Text;
using TriconexToTia.Core.Enums;
using TriconexToTia.Core.Interfaces;
using TriconexToTia.Core.Results;

namespace TriconexToTia.Generators;

/// <summary>Emits the import.ps1 script the TIA Portal operator runs.</summary>
public sealed class ImportScriptGenerator : IGenerator
{
    public string Id => "import-script";

    public string Description => "TIA Portal Openness import script";

    public IEnumerable<GeneratedFile> Generate(GenerationContext context)
    {
        var options = context.Options;
        var version = options.ClampTiaVersion();
        var cpu = string.IsNullOrWhiteSpace(options.PlcCpu) ? string.Empty : options.PlcCpu!.Trim();
        var source = string.IsNullOrWhiteSpace(context.Project.SourceFile) ? "Triconex XML" : context.Project.SourceFile;
        var stamp = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");

        var script = Template
            .Replace("__TIA_VERSION__", version.ToString())
            .Replace("__CPU__", cpu)
            .Replace("__DATE__", stamp)
            .Replace("__SOURCE__", source);

        yield return new GeneratedFile
        {
            RelativePath = "import.ps1",
            Content = script,
            Kind = ArtifactKind.Script,
            EmitBom = true,
        };
    }

    private const string Template = @"#Requires -Version 5.1
<#
.SYNOPSIS
    Imports a converted Triconex project into Siemens TIA Portal.

.DESCRIPTION
    Generated by the TriconexToTia converter tool on __DATE__.
    Source: __SOURCE__
    Target: TIA Portal V__TIA_VERSION__.

    Run this script on a machine with TIA Portal V__TIA_VERSION__ installed. The
    Windows user running it must be a member of the local group
    ""Siemens TIA Openness"".

.NOTES
    The generated package must keep its folder layout: Blocks/, UDTs/, Tags/.
    Hardware configuration is NOT created automatically unless -CpuOrderNumber is
    supplied; add the CPU and I/O modules first, or pass the order number.
#>
[CmdletBinding()]
param(
    [string]$ProjectName = ""ConvertedProject"",
    [string]$ProjectPath = ""C:\TIA_Projects"",
    [string]$TiaInstallPath = ""C:\Program Files\Siemens\Automation\Portal V__TIA_VERSION__"",
    [string]$CpuOrderNumber = ""__CPU__""
)

$ErrorActionPreference = ""Stop""
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path

$opennessPath = Join-Path $TiaInstallPath ""PublicAPI\V__TIA_VERSION__\Siemens.Engineering.dll""
if (-not (Test-Path -LiteralPath $opennessPath)) {
    Write-Error ""TIA Portal V__TIA_VERSION__ not found at '$TiaInstallPath'.""
    Write-Error ""Set -TiaInstallPath to your installation, e.g. 'C:\Program Files\Siemens\Automation\Portal V__TIA_VERSION__'.""
    exit 1
}

Add-Type -Path $opennessPath

function Get-PlcSoftware {
    param($Device)
    foreach ($item in $Device.DeviceItems) {
        try {
            $container = $item.GetService([Siemens.Engineering.SW.ISoftwareContainer])
            if ($null -ne $container -and $null -ne $container.Software) { return $container.Software }
        } catch {
            # Not a software container; keep looking.
        }
    }
    return $null
}

Write-Host ""Starting TIA Portal V__TIA_VERSION__..."" -ForegroundColor Cyan
$tia = New-Object Siemens.Engineering.TiaPortal([Siemens.Engineering.TiaPortalMode]::WithoutUserInterface)

try {
    $fullProjectPath = Join-Path $ProjectPath $ProjectName
    if (-not (Test-Path -LiteralPath $ProjectPath)) {
        New-Item -ItemType Directory -Path $ProjectPath -Force | Out-Null
    }

    Write-Host ""Creating project '$ProjectName' at '$fullProjectPath'..."" -ForegroundColor Cyan
    $project = $tia.Projects.Create($fullProjectPath, $ProjectName)

    $plcSoftware = $null
    if (-not [string]::IsNullOrWhiteSpace($CpuOrderNumber)) {
        if ($CpuOrderNumber -notlike ""OrderNumber:*"") {
            $CpuOrderNumber = ""OrderNumber:$CpuOrderNumber""
        }
        Write-Host ""Adding PLC device: $CpuOrderNumber"" -ForegroundColor Cyan
        $device = $project.Devices.CreateWithItem($CpuOrderNumber, ""PLC_1"", ""PLC_1"")
        $plcSoftware = Get-PlcSoftware $device
    }

    if ($null -eq $plcSoftware) {
        Write-Warning ""No PLC software found. Add a PLC device in TIA Portal, or pass -CpuOrderNumber.""
        Write-Warning ""Re-run this script after the device exists, or set -CpuOrderNumber to the CPU order number.""
        $project.Save()
        return
    }

    # 1. UDTs first — blocks and tags may reference them.
    $udtDir = Join-Path $ScriptDir ""UDTs""
    if (Test-Path -LiteralPath $udtDir) {
        Write-Host ""Importing UDTs..."" -ForegroundColor Cyan
        Get-ChildItem -LiteralPath $udtDir -Filter *.xml | Sort-Object Name | ForEach-Object {
            Write-Host ""  UDT: $($_.Name)""
            $plcSoftware.TypeGroup.Types.Import($_.FullName, [Siemens.Engineering.ImportOptions]::Override)
        }
    }

    # 2. Global tag tables.
    $tagDir = Join-Path $ScriptDir ""Tags""
    if (Test-Path -LiteralPath $tagDir) {
        Write-Host ""Importing tag tables..."" -ForegroundColor Cyan
        Get-ChildItem -LiteralPath $tagDir -Filter *.xml | Sort-Object Name | ForEach-Object {
            Write-Host ""  Tags: $($_.Name)""
            $plcSoftware.TagTableGroup.TagTables.Import($_.FullName, [Siemens.Engineering.ImportOptions]::Override)
        }
    }

    # 3. SCL blocks via external source files, then generate.
    $blockDir = Join-Path $ScriptDir ""Blocks""
    if (Test-Path -LiteralPath $blockDir) {
        Write-Host ""Importing blocks..."" -ForegroundColor Cyan
        $sourceGroup = $plcSoftware.ExternalSourceGroup
        Get-ChildItem -LiteralPath $blockDir -Filter *.scl | Sort-Object Name | ForEach-Object {
            Write-Host ""  Block: $($_.Name)""
            $external = $sourceGroup.ExternalSources.CreateFromFile($_.BaseName, $_.FullName)
            $external.GenerateBlocksFromSource()
        }
    }

    # 4. Compile.
    Write-Host ""Compiling..."" -ForegroundColor Cyan
    $compileService = $plcSoftware.GetService([Siemens.Engineering.Compiler.CompilerService])
    $result = $compileService.Compile()
    if ($result.State -ne [Siemens.Engineering.Compiler.CompilerResultState]::Success) {
        Write-Warning ""Compilation finished with state: $($result.State)""
    }

    Write-Host ""Saving project..."" -ForegroundColor Cyan
    $project.Save()

    Write-Host """"
    Write-Host ""Import complete: $fullProjectPath"" -ForegroundColor Green
    Write-Host ""Review conversion_report.txt for manual actions before use."" -ForegroundColor Yellow
}
catch {
    Write-Error ""Import failed: $($_.Exception.Message)""
    throw
}
finally {
    if ($null -ne $tia) { $tia.Dispose() }
}
";
}
